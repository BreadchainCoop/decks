#!/usr/bin/env node
/** Reproducible, dependency-free Apps Script bundle. No deployment or secrets.
 * node apps-script/build-suite.cjs [output-file]
 */
const fs = require("node:fs"), path = require("node:path"), vm = require("node:vm");
const root = __dirname;
function read(name) { return fs.readFileSync(path.join(root,name),"utf8"); }
function once(text, from, to) {
  if(text.split(from).length !== 2) throw new Error("Expected exactly one bundle transform: "+from);
  return text.replace(from,to);
}
function build(){
  let work=read("work-tracker-write.gs");
  work=once(work,"function doPost(e)","function breadLegacyWorkPost_(e)");
  work=once(work,"function doGet(e)","function breadLegacyWorkGet_(e)");
  const globals={SPREADSHEET_ID:"WORK_SPREADSHEET_ID",CONTRIB_SPREADSHEET_ID:"CONTRIB_SPREADSHEET_ID",TOKEN:"BREAD_WRITE_TOKEN"};
  for(const [name,prop] of Object.entries(globals)){
    const regex=new RegExp('^var '+name+' = "[^"\\r\\n]*";','m');
    if(!regex.test(work)) throw new Error("Missing work configuration: "+name);
    work=work.replace(regex,`var ${name} = PropertiesService.getScriptProperties().getProperty("${prop}") || "";`);
  }
  let crm=once(read("crm-write.gs"),"function doPost(event)","function breadStandaloneCrmPost_(event)");
  let lib=read("bh-lib.gs");
  for(const id of ["10vQRSVpiePANd1yNzSyua_PO5DCgk9muB_VqYIFDAkE","1ncGbPZyf0vH9NCsndvaUkmkJremWz1YW1_-YPpLRjxA","19Lxe0C14BOYbOj0Z0nyoQc4-I_aw_jgybcq9LggfcUw"]){
    lib=once(lib,', "'+id+'");',', "");');
  }
  let result="/** GENERATED by build-suite.cjs — edit source modules, then rebuild. */\nvar BREAD_SUITE_BUILD = true;\n"+
    [work,crm,lib,...["crm-migration.gs","crm-feed.gs","hq-service.gs","hq-budget.gs","grants-service.gs","grants-feed.gs","grants-pipeline-tab.gs","jobs-work.gs","jobs-crm.gs","jobs-contributors.gs","jobs-suite.gs","jobs-github.gs","jobs-grants.gs","install-suite-triggers.gs","staging-config.gs","suite-web.gs"].map(read)].join("\n\n");
  new vm.Script(result,{filename:"BreadSuite.gs"});
  for(const handler of ["doPost","doGet"]){
    if((result.match(new RegExp("function "+handler+"\\(","g"))||[]).length !== 1)throw new Error("Duplicate "+handler);
  }
  return result;
}
if(require.main===module){
  const out=process.argv[2]||path.join(root,"dist","Code.gs");
  const result=build();fs.mkdirSync(path.dirname(out),{recursive:true});fs.writeFileSync(out,result);
  console.log("Built suite:",out,Buffer.byteLength(result),"bytes");
}
module.exports={build};
